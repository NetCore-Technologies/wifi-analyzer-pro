#!/usr/bin/env bash
set -Eeuo pipefail

ROOT="$(git rev-parse --show-toplevel 2>/dev/null)" || {
  echo "Run this command from inside the existing WiFi Analyzer Pro checkout." >&2
  exit 2
}
cd "$ROOT"

[[ "$(git branch --show-current)" == "main" ]] || {
  echo "This pack only targets the existing main branch. No branch will be created." >&2
  exit 2
}
[[ -z "$(git diff --cached --name-only)" ]] || {
  echo "The Git index already contains staged changes. Commit or unstage them first." >&2
  exit 2
}
git remote get-url origin >/dev/null 2>&1 || {
  echo "The origin remote is missing; refusing to create the commit series." >&2
  exit 2
}

# Use the user's normal identity and signing key. We do not rewrite authors,
# dates, signatures, or commit metadata to disguise how changes were made.
git config user.name >/dev/null || { echo "Set your normal git user.name first." >&2; exit 2; }
git config user.email >/dev/null || { echo "Set your normal git user.email first." >&2; exit 2; }
if [[ "$(git config --get gpg.format || echo openpgp)" != "ssh" ]] && ! command -v gpg >/dev/null 2>&1; then
  echo "A GPG or SSH signing setup is required by main's required-signatures ruleset." >&2
  exit 2
fi

# Fetch and anchor the sequence to the current remote main. Resuming is allowed
# only when any existing ahead commits are signed and already belong to this pack.
git fetch --quiet origin main
BASE="$(git rev-parse origin/main)"
if ! git merge-base --is-ancestor "$BASE" HEAD; then
  echo "Local main has diverged from origin/main. Reconcile first; no commits created." >&2
  exit 2
fi
AHEAD="$(git rev-list --count "$BASE..HEAD")"
if (( AHEAD != 0 )); then
  echo "Start from a clean local main exactly at origin/main (found $AHEAD local commits ahead)." >&2
  echo "Do not mix this 50-commit series with prior local work." >&2
  exit 2
fi

# Reject unrelated modifications before applying our guarded, idempotent patches.
while IFS= read -r changed_path; do
  case "$changed_path" in
    package.json|vite.config.js|Dockerfile|README.md|.github/workflows/release.yml|wifi_analyzer_backend/build_arm64_binary.sh|wifi_analyzer_backend/server.py|wifi_analyzer_backend/auth.py|wifi_analyzer_backend/feature_plugins/*|tests/test_auth.py|tests/test_feature_plugins.py|scripts/apply_feature_pack.py|scripts/patch_ui_truthfulness.py|scripts/commit_features.sh|scripts/push_main.sh|FEATURES_100.md|COMMITS_50.md|README_50_COMMITS.md|src/App.jsx|src/main.jsx|src/hooks/useWifiData.js|src/auth/*|src/lib/api.js|src/components/FeatureWorkbench.jsx)
      ;;
    *)
      echo "Unexpected changed path '$changed_path'. Reconcile unrelated work before continuing." >&2
      exit 2
      ;;
  esac
done < <(git status --porcelain=v1 | sed -E 's/^...//')

# Apply the integration exactly once; both scripts stop on unknown source layouts.
python3 scripts/apply_feature_pack.py
python3 scripts/patch_ui_truthfulness.py

# Keep generated bytecode out of commits and archives.
find wifi_analyzer_backend tests scripts -type d -name __pycache__ -prune -exec rm -rf {} +
find wifi_analyzer_backend tests scripts -type f -name '*.pyc' -delete

mapfile -t MODULES < <(find wifi_analyzer_backend/feature_plugins -maxdepth 1 -type f -name 'feature_[0-9][0-9][0-9]_*.py' | sort)
if [[ "${#MODULES[@]}" -ne 100 ]]; then
  echo "Expected exactly 100 independently implemented feature modules; found ${#MODULES[@]}." >&2
  exit 2
fi
python3 - <<'PY'
import json
from pathlib import Path
manifest = json.loads(Path("wifi_analyzer_backend/feature_plugins/FEATURES.json").read_text(encoding="utf-8"))
if len(manifest) != 100 or len({item["slug"] for item in manifest}) != 100:
    raise SystemExit("Feature manifest must contain exactly 100 unique tool definitions")
PY

# Validate the complete working tree before creating any commits.
python3 -m compileall -q wifi_analyzer_backend tests
python3 -m unittest discover -s tests -v
if [[ "${SKIP_FRONTEND_CHECKS:-0}" != "1" ]]; then
  npm ci --no-audit --no-fund
  npm run lint
  npm run build
else
  echo "WARNING: frontend checks explicitly skipped. Do not push this series until npm lint/build pass." >&2
fi
git diff --check

commit_staged() {
  local message="$1"
  if git diff --cached --quiet; then
    echo "[skip] $message (already committed)"
  else
    git diff --cached --check
    git commit -S -m "$message"
  fi
}

# Commit 1: all integration plumbing plus the first two real tools.
# The remaining 98 tools are then introduced as 49 small, two-tool commits.
git add \
  package.json vite.config.js Dockerfile README.md \
  .github/workflows/release.yml wifi_analyzer_backend/build_arm64_binary.sh \
  wifi_analyzer_backend/server.py wifi_analyzer_backend/auth.py \
  wifi_analyzer_backend/feature_plugins/__init__.py \
  wifi_analyzer_backend/feature_plugins/common.py \
  wifi_analyzer_backend/feature_plugins/registry.py \
  wifi_analyzer_backend/feature_plugins/FEATURES.json \
  tests/test_auth.py tests/test_feature_plugins.py \
  scripts/apply_feature_pack.py scripts/patch_ui_truthfulness.py \
  scripts/commit_features.sh scripts/push_main.sh \
  FEATURES_100.md COMMITS_50.md README_50_COMMITS.md \
  src/App.jsx src/main.jsx src/hooks/useWifiData.js \
  src/auth/AuthContext.jsx src/auth/AuthGate.jsx \
  src/lib/api.js src/components/FeatureWorkbench.jsx \
  "${MODULES[0]}" "${MODULES[1]}"
commit_staged "feat: add feature engine, local login, and core discovery tools"

# Each of the remaining 49 commits adds exactly two feature modules.
for ((index=2; index<100; index+=2)); do
  first="${MODULES[$index]}"
  second="${MODULES[$((index+1))]}"
  first_slug="$(basename "$first" .py | sed -E 's/^feature_[0-9]{3}_//; s/_/ /g')"
  second_slug="$(basename "$second" .py | sed -E 's/^feature_[0-9]{3}_//; s/_/ /g')"
  git add -- "$first" "$second"
  commit_staged "feat: add ${first_slug} and ${second_slug}"
done

# Final checks enforce exactly 50 real, signed commits with two tool files each.
AHEAD="$(git rev-list --count "$BASE..HEAD")"
if [[ "$AHEAD" -ne 50 ]]; then
  echo "Expected exactly 50 commits ahead of origin/main; found $AHEAD. Do not push." >&2
  exit 1
fi
if [[ -n "$(git status --porcelain)" ]]; then
  echo "The worktree is not clean after the commit series. Reconcile before pushing." >&2
  exit 1
fi
if git log --format='%G?' "$BASE..HEAD" | grep -qv '^G$'; then
  echo "At least one commit is not locally signature-verified. Do not push." >&2
  exit 1
fi

# Ensure every numbered plugin file was introduced exactly once, and each commit
# in the series introduces exactly two of them.
for file in "${MODULES[@]}"; do
  [[ "$(git log --format=%H "$BASE..HEAD" -- "$file" | wc -l)" -eq 1 ]] || {
    echo "Expected exactly one commit introducing $file." >&2
    exit 1
  }
done
while IFS= read -r commit; do
  count="$(git diff-tree --no-commit-id --name-only -r "$commit" | grep -Ec '^wifi_analyzer_backend/feature_plugins/feature_[0-9]{3}_.+\.py$' || true)"
  [[ "$count" -eq 2 ]] || {
    echo "Commit $commit introduces $count feature modules (expected two). Do not push." >&2
    exit 1
  }
done < <(git rev-list --reverse "$BASE..HEAD")

python3 -m compileall -q wifi_analyzer_backend tests
python3 -m unittest discover -s tests -v
if [[ "${SKIP_FRONTEND_CHECKS:-0}" != "1" ]]; then
  npm run lint
  npm run build
fi
git diff --check

echo "Created exactly 50 signed commits on the existing main branch: two distinct feature modules per commit (100 modules total)."
echo "Nothing has been pushed or released. Review with: git log --oneline --reverse origin/main..HEAD"
echo "When ready, run: bash scripts/push_main.sh"
